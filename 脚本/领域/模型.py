"""
DDD 领域模型核心 - 纯净 Python，零框架依赖
包含：胜平负赔率值对象、时序位移值对象、单场比赛心电图聚合根实体
"""
from dataclasses import dataclass
from typing import Tuple


@dataclass(frozen=True)
class 赔率数值:
    """值对象：不可变的胜平负数值"""
    主胜: float
    平局: float
    客胜: float

    def __post_init__(self):
        if self.主胜 <= 0 or self.平局 <= 0 or self.客胜 <= 0:
            raise ValueError("赔率数值必须大于零")

    def 去水公平概率(self) -> Tuple[float, float, float]:
        """按 Shin/去抽水归一化算法反推真实无抽水平率"""
        倒数主 = 1.0 / self.主胜
        倒数平 = 1.0 / self.平局
        倒数客 = 1.0 / self.客胜
        抽水率 = (倒数主 + 倒数平 + 倒数客) - 1.0
        归一因子 = 1.0 + 抽水率
        return (倒数主 / 归一因子, 倒数平 / 归一因子, 倒数客 / 归一因子)


@dataclass(frozen=True)
class 赔率位移:
    """值对象：两点之间的位移量与变盘加速度"""
    平赔变动值: float
    每小时变盘速率: float
    异动信号: str

    def 是否显著防守降水(self) -> bool:
        """平赔断崖跳水超过 0.15 即触发避险阈值（伪降水诱平严禁判定为避险）"""
        if self.异动信号 == "伪降水诱平掩护客胜":
            return False
        return self.平赔变动值 <= -0.15


@dataclass
class 赔率快照:
    """聚合根实体：带时间戳与赛事身份的心电图观测点"""
    比赛编号: str
    竞彩场次: str  # 例如: "周一002"
    对阵名称: str  # 例如: "赫塔费 vs 塞尔塔"
    联赛名称: str
    赔率: 赔率数值
    记录时间戳: int
    官方浮动标记: int  # -1 降水, 0 未变, 1 升水

    def 计算位移(self, 早期快照: "赔率快照") -> 赔率位移:
        """富领域模型核心行为：计算连续轨迹的倾斜角与定性"""
        变动 = self.赔率.平局 - 早期快照.赔率.平局
        小时差 = max(1.0 / 3600.0, (self.记录时间戳 - 早期快照.记录时间戳) / 3600.0)
        速率 = 变动 / 小时差

        if 变动 < 0:
            # 严格判别伪降水：客胜水位低于主胜水位时，平赔下调实为诱平掩护客胜
            if self.赔率.客胜 < self.赔率.主胜 and 变动 <= -0.05:
                信号 = "伪降水诱平掩护客胜"
            elif 变动 <= -0.15:
                信号 = "机构死守避险降水"
            else:
                信号 = "中性平稳横盘"
        elif 变动 >= 0.20:
            # 极热假深盘诱主：强队胜赔<=1.40且平赔大幅推高>=0.20
            if self.赔率.主胜 <= 1.40:
                信号 = "极热假深盘诱主阻平"
            else:
                信号 = "拉高阻盘通吃诱两头"
        else:
            信号 = "中性平稳横盘"

        return 赔率位移(
            平赔变动值=变动,
            每小时变盘速率=速率,
            异动信号=信号
        )


def 校验让球明牌平局对冲资格(
    受让方场均客场失球: float,
    豪门休赛天数: float = 7.0,
    豪门预期进球xG: float = 2.0
) -> Tuple[bool, str]:
    """
    红线 7 庄家明牌开卷考物理断路器：
    体彩故意关闭胜平负仅开让球盘时，严禁无脑逆势买平！
    必须同时满足受让方为顶级铁桶 (失球 <= 0.8) 或豪门体能枯竭 (休赛 <= 3 天)；
    若受让方防守漏风 (失球 > 1.2) 且豪门火力无损 (xG >= 2.5)，让胜穿盘概率近 40%，一票否决！
    """
    if 受让方场均客场失球 <= 0.8:
        return True, "合格：受让方具备顶级铁桶防守韧性 (客场失球<=0.8)"
    if 豪门休赛天数 <= 3.0:
        return True, "合格：豪门双赛周体能严重枯竭 (休赛<=3天)"
    if 受让方场均客场失球 > 1.2 and 豪门预期进球xG >= 2.5:
        return False, "一票否决：受让方防守漏洞且豪门战力断层碾压，让胜穿盘率极高，严禁逆势买平"
    return False, "一票否决：受让方防守未达铁桶标准且豪门体能齐整，严禁盲目反向买平"


def 校验攻防伤停平局资格(
    进攻核心缺阵: bool,
    后腰防线对抗率: float,
    主队场均失球: float = 1.0
) -> Tuple[bool, str]:
    """
    攻防伤停平衡物理断路器 (防 017 式假闷平崩盘)：
    前场进攻核心缺阵不仅影响进球，更导致前场第一道就地反抢大闸消失；
    必须同时核验后腰与防线对抗胜率 (>= 65%)；
    若后腰对抗率 < 60% 无法拦截反击，中场失控必被打穿分胜负，一票否决！
    """
    if 进攻核心缺阵 and 后腰防线对抗率 < 0.60:
        return False, "一票否决：前场进攻核心缺阵且后腰防线对抗率不足60%，中场失控必被反击打穿，严禁单挑假闷平"
    return True, "合格：防守屏障稳固或攻防平衡"
