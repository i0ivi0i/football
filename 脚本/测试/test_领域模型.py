import pytest
from 领域.模型 import 赔率数值, 赔率快照, 赔率位移


def test_赔率数值验证与去水计算():
    赔率 = 赔率数值(主胜=2.37, 平局=2.58, 客胜=3.13)
    assert 赔率.主胜 == 2.37
    assert 赔率.平局 == 2.58
    assert 赔率.客胜 == 3.13

    # Shin / 去抽水无抽水平率反推
    主率, 平率, 客率 = 赔率.去水公平概率()
    assert round(平率 * 100, 2) == 34.33
    assert round((主率 + 平率 + 客率), 2) == 1.00


