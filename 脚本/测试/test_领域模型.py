import pytest
from 领域.模型 import 赔率数值, 赔率快照, 赔率位移


def test_赔率数值验证与去水计算():
    赔率 = 赔率数值(主胜=2.37, 平局=2.58, 客胜=3.13)
    assert 赔率.主胜 == 2.37
    assert 赔率.平局 == 2.58
    assert 赔率.客胜 == 3.13

    # Shin / 去抽水无抽水平率反推
    主率, 平率, 客率 = 赔率.去水公平概率()
    assert round(平率 * 100, 2) == 34.33
    assert round((主率 + 平率 + 客率), 2) == 1.00


def test_赔率数值拒绝非正数非法输入():
    with pytest.raises(ValueError, match="赔率数值必须大于零"):
        赔率数值(主胜=-1.0, 平局=2.5, 客胜=3.0)


def test_赔率快照计算连续位移与异动信号():
    早期 = 赔率快照(
        比赛编号="2041321",
        竞彩场次="周一002",
        对阵名称="赫塔费 vs 塞尔塔",
        联赛名称="西甲",
        赔率=赔率数值(主胜=2.50, 平局=3.10, 客胜=2.90),
        记录时间戳=1000,
        官方浮动标记=0
    )
    晚期 = 赔率快照(
        比赛编号="2041321",
        竞彩场次="周一002",
        对阵名称="赫塔费 vs 塞尔塔",
        联赛名称="西甲",
        赔率=赔率数值(主胜=2.37, 平局=2.58, 客胜=3.13),
        记录时间戳=4600,
        官方浮动标记=-1
    )

    位移: 赔率位移 = 晚期.计算位移(早期)
    assert round(位移.平赔变动值, 2) == -0.52
    assert 位移.异动信号 == "机构死守避险降水"
    assert 位移.是否显著防守降水() is True
