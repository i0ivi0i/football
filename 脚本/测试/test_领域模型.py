def test_深盘冷平放行资格防003_006_012_022机械误杀():
    """断言强队胜赔<1.60时，若满足铁桶、多赛疲劳或高平阻盘，严禁机械枪毙，必须放行"""
    from 领域.模型 import 校验深盘冷平放行资格

    # 1. 类似周日003塞尔塔vs马拉加 (塞尔塔 1.53, 马拉加客场失球 0.85) -> 放行
    放行, 原因 = 校验深盘冷平放行资格(强方胜赔=1.53, 平局赔率=3.50, 弱方场均失球=0.85)
    assert 放行 is True
    assert "放行" in 原因

    # 2. 类似周日006海伦芬vs特尔斯达 (海伦芬 1.41, 平赔 4.55 高平阻盘) -> 放行
    放行, 原因 = 校验深盘冷平放行资格(强方胜赔=1.41, 平局赔率=4.55)
    assert 放行 is True
    assert "高平阻盘" in 原因

    # 3. 类似周日012勒芒vs朗斯 (朗斯客胜 1.44, 欧战多赛休赛 3 天) -> 放行
    放行, 原因 = 校验深盘冷平放行资格(强方胜赔=1.44, 平局赔率=4.15, 强方休赛天数=3.0)
    assert 放行 is True
    assert "多赛" in 原因

    # 4. 纯粹实力断层碾压局 (强方胜赔 1.25, 弱方失球 2.50, 体能充沛休赛 7 天, 平赔 6.00) -> 排除
    放行, 原因 = 校验深盘冷平放行资格(强方胜赔=1.25, 平局赔率=6.00, 弱方场均失球=2.50, 强方休赛天数=7.0)
    assert 放行 is False

