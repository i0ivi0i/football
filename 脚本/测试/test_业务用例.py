import pytest
from typing import List, Optional

from 领域.模型 import 赔率数值, 赔率快照
from 领域.契约 import 赔率提供者契约, 赔率账本契约
from 应用.用例 import 探测并记录心电图用例, 回溯连续轨迹用例


class 内存模拟提供者(赔率提供者契约):
    def __init__(self, 快照列表: List[赔率快照]):
        self._快照列表 = 快照列表

    def 抓取当前快照列表(self) -> List[赔率快照]:
        return self._快照列表


class 内存模拟账本(赔率账本契约):
    def __init__(self):
        self._流水: List[赔率快照] = []

    def 批量保存快照(self, 快照列表: List[赔率快照]) -> None:
        self._流水.extend(快照列表)

    def 查询比赛连续轨迹(self, 竞彩场次: str) -> List[赔率快照]:
        return [快照 for 快照 in self._流水 if 快照.竞彩场次 == 竞彩场次]

    def 获取最新快照(self, 竞彩场次: str) -> Optional[赔率快照]:
        匹配 = self.查询比赛连续轨迹(竞彩场次)
        return 匹配[-1] if 匹配 else None


def test_探测并记录心电图用例捕获异动跳水():
    账本 = 内存模拟账本()
    初盘快照 = 赔率快照(
        比赛编号="2041321",
        竞彩场次="周一002",
        对阵名称="赫塔费 vs 塞尔塔",
        联赛名称="西甲",
        赔率=赔率数值(主胜=2.50, 平局=3.10, 客胜=2.90),
        记录时间戳=1000,
        官方浮动标记=0
    )
    账本.批量保存快照([初盘快照])

    现盘快照 = 赔率快照(
        比赛编号="2041321",
        竞彩场次="周一002",
        对阵名称="赫塔费 vs 塞尔塔",
        联赛名称="西甲",
        赔率=赔率数值(主胜=2.37, 平局=2.58, 客胜=3.13),
        记录时间戳=8200,
        官方浮动标记=-1
    )
    提供者 = 内存模拟提供者([现盘快照])

    用例 = 探测并记录心电图用例(提供者=提供者, 账本=账本)
    结果 = 用例.执行()

    assert 结果.入库数量 == 1
    assert len(结果.异常异动警报) == 1
    assert 结果.异常异动警报[0].异动信号 == "机构死守避险降水"
    assert round(结果.异常异动警报[0].平赔变动值, 2) == -0.52


def test_回溯连续轨迹用例提炼单边变盘态势():
    账本 = 内存模拟账本()
    s1 = 赔率快照("1", "周一002", "赫塔费 vs 塞尔塔", "西甲", 赔率数值(2.5, 3.2, 2.9), 1000, 0)
    s2 = 赔率快照("1", "周一002", "赫塔费 vs 塞尔塔", "西甲", 赔率数值(2.4, 2.9, 3.0), 2000, -1)
    s3 = 赔率快照("1", "周一002", "赫塔费 vs 塞尔塔", "西甲", 赔率数值(2.37, 2.58, 3.13), 3000, -1)
    账本.批量保存快照([s1, s2, s3])

    分析用例 = 回溯连续轨迹用例(账本=账本)
    结果 = 分析用例.分析单场("周一002")

    assert 结果.采样次数 == 3
    assert 结果.累计平赔位移 == round(2.58 - 3.20, 2)
    assert 结果.趋势定性 == "持续单边阴跌 (机构实防关门)"
