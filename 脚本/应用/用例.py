from dataclasses import dataclass
from typing import List

from 领域.模型 import 赔率快照, 赔率位移
from 领域.契约 import 赔率提供者契约, 赔率账本契约


@dataclass
class 记录结果:
    入库数量: int
    异常异动警报: List[赔率位移]


@dataclass
class 轨迹结果:
    竞彩场次: str
    采样次数: int
    累计平赔位移: float
    趋势定性: str
    历史快照列表: List[赔率快照]


class 探测并记录心电图用例:
    """业务用例：定时探测盘口，自动与上一时刻比对位移，发现异动报警并落库"""

    def __init__(self, 提供者: 赔率提供者契约, 账本: 赔率账本契约):
        self.提供者 = 提供者
        self.账本 = 账本

    def 执行(self) -> 记录结果:
        当前快照列表 = self.提供者.抓取当前快照列表()
        警报列表: List[赔率位移] = []

        for 当前 in 当前快照列表:
            早期 = self.账本.获取最新快照(当前.竞彩场次)
            if 早期:
                位移 = 当前.计算位移(早期)
                if 位移.是否显著防守降水() or 位移.异动信号 != "中性平稳横盘":
                    警报列表.append(位移)

        self.账本.批量保存快照(当前快照列表)
        return 记录结果(入库数量=len(当前快照列表), 异常异动警报=警报列表)


class 回溯连续轨迹用例:
    """业务用例：对特定场次调取从初盘到终盘的全部时序数据并提炼态势"""

    def __init__(self, 账本: 赔率账本契约):
        self.账本 = 账本

    def 分析单场(self, 竞彩场次: str) -> 轨迹结果:
        记录 = self.账本.查询比赛连续轨迹(竞彩场次)
        if not 记录:
            return 轨迹结果(
                竞彩场次=竞彩场次,
                采样次数=0,
                累计平赔位移=0.0,
                趋势定性="暂无数据",
                历史快照列表=[]
            )

        首盘 = 记录[0]
        末盘 = 记录[-1]
        累计位移 = round(末盘.赔率.平局 - 首盘.赔率.平局, 2)

        if 累计位移 <= -0.20:
            态势 = "持续单边阴跌 (机构实防关门)"
        elif 累计位移 >= 0.25:
            态势 = "持续单边诱升 (机构阻盘杀两头)"
        else:
            态势 = "平稳横盘震荡"

        return 轨迹结果(
            竞彩场次=竞彩场次,
            采样次数=len(记录),
            累计平赔位移=累计位移,
            趋势定性=态势,
            历史快照列表=记录
        )
